function srtTimestamp(seconds) {
  const totalMs = Math.max(0, Math.round(seconds * 1000));
  const hours = String(Math.floor(totalMs / 3_600_000)).padStart(2, "0");
  const minutes = String(Math.floor((totalMs % 3_600_000) / 60_000)).padStart(2, "0");
  const secs = String(Math.floor((totalMs % 60_000) / 1000)).padStart(2, "0");
  const ms = String(totalMs % 1000).padStart(3, "0");
  return `${hours}:${minutes}:${secs},${ms}`;
}

export function inquiryTypeTicks(video) {
  const baseName = video.baseName || (video.name || "").replace(/-light$/, "");
  const isIntro = baseName === "inquiry-intro" || video.duration <= 36;
  const speed = isIntro ? 0.90 : 1.15;
  const ticks = [];
  const pushBurst = (tStart, dur, count, maxTime) => {
    const step = dur / Math.max(1, count);
    for (let k = 0; k < count; k++) {
      const jitter = ((k * 3) % 5 - 2) * 0.003;
      const t = tStart + k * step + jitter;
      if (t > 0.05 && t < maxTime) {
        ticks.push(Number(t.toFixed(3)));
      }
    }
  };
  for (const caption of video.captions || []) {
    const s = caption.start;
    const limit = Math.min(caption.end - 0.25, video.duration - 0.35);
    // Stage 1: Eyebrow
    pushBurst(s + 0.02 * speed, 0.28 * speed, 5, limit);
    // Stage 2: Headline lines
    const lines = caption.lines || [];
    lines.forEach((lineText, lIdx) => {
      const lStart = s + (0.18 + lIdx * 0.44) * speed;
      const lCount = Math.min(11, Math.max(6, Math.round(lineText.length / 4)));
      pushBurst(lStart, 0.40 * speed, lCount, limit);
    });
    // Stage 3: Sub-statement
    const notes = caption.notes || (caption.note ? [caption.note] : []);
    const noteStart = (0.20 + lines.length * 0.44) * speed;
    notes.forEach((noteLine, nIdx) => {
      const nStart = s + noteStart + nIdx * 0.44 * speed;
      const nCount = Math.min(12, Math.max(7, Math.round(noteLine.length / 5)));
      pushBurst(nStart, 0.43 * speed, nCount, limit);
    });
    // Stage 4: Process formula (`axiom`)
    if (caption.axiom) {
      const axStart = s + noteStart + notes.length * 0.44 * speed + 0.04 * speed;
      pushBurst(axStart, 0.36 * speed, 8, limit);
    }
  }
  return ticks;
}

export function inquirySubtitles(video) {
  return video.captions
    .map((caption, index) => {
      const notes = caption.notes || (caption.note ? [caption.note] : []);
      return [
        index + 1,
        `${srtTimestamp(caption.start)} --> ${srtTimestamp(caption.end)}`,
        caption.lines.join(" "),
        ...notes,
        "",
      ].join("\n");
    })
    .join("\n");
}


  function recordBounds(text, x, y, width, size, align, track = true) {
    if (!track) return;
    const left = align === "center" ? x - width / 2 : align === "right" ? x - width : x;
    const right = left + width;
    const top = y - size * 0.88;
    const bottom = y + size * 0.28;
    textBounds.push({ text: String(text), left, right, top, bottom, size, region: textRegion });
  }

  function tokenizeFocusTerm(str, baseColor, focusTerm, focusColor = focusHighlight) {
    if (!focusTerm) return [{ start: 0, end: str.length, color: baseColor }];
    const idx = str.indexOf(focusTerm);
    if (idx === -1) return [{ start: 0, end: str.length, color: baseColor }];
    const segments = [];
    if (idx > 0) {
      segments.push({ start: 0, end: idx, color: baseColor });
    }
    segments.push({
      start: idx,
      end: idx + focusTerm.length,
      color: focusColor,
    });
    if (idx + focusTerm.length < str.length) {
      segments.push({ start: idx + focusTerm.length, end: str.length, color: baseColor });
    }
    return segments;
  }

  function type(text, x, y, size, {
    color = deepInk,
    alpha = 1,
    family = "Inter",
    weight = 600,
    style = "normal",
    align = "left",
    progress = 1,
    caret = false,
    caretColor = warmGold,
    caretAlpha = 0.92,
    focusTerm = null,
    focusColor = focusHighlight,
    halo = null,
    haloWidth = 6,
    track = true,
    maxWidth = null,
    letterSpacing = null,
  } = {}) {
    if (alpha <= 0.001 || progress <= 0.001 || !text) return;
    const p = clamp(progress);
    const str = String(text);
    ctx.save();
    let finalSize = size;
    if (letterSpacing !== null && "letterSpacing" in ctx) {
      ctx.letterSpacing = letterSpacing;
    } else if ("letterSpacing" in ctx) {
      ctx.letterSpacing = isTrailer ? "0px" : family === "JetBrains Mono" ? "0.04em" : finalSize >= 34 ? "-0.022em" : "-0.008em";
    }
    ctx.font = `${style} ${weight} ${finalSize}px "${family}", sans-serif`;
    let fullWidth = ctx.measureText(str).width;
    if (maxWidth && fullWidth > maxWidth) {
      finalSize = Math.max(12, size * (maxWidth / fullWidth) * 0.98);
      ctx.font = `${style} ${weight} ${finalSize}px "${family}", sans-serif`;
      fullWidth = ctx.measureText(str).width;
    }
    recordBounds(str, x, y, fullWidth, finalSize, align, track);

    const startX = align === "center" ? x - fullWidth / 2 : align === "right" ? x - fullWidth : x;
    ctx.textAlign = "left";

    const isDone = p >= 0.999;
    const exact = str.length * p;
    const wholeCount = isDone ? str.length : Math.floor(exact);
    const frac = isDone ? 0 : exact - wholeCount;
    const segments = tokenizeFocusTerm(str, color, focusTerm, focusColor);

    for (const seg of segments) {
      if (seg.start < wholeCount) {
        const subEnd = Math.min(seg.end, wholeCount);
        const sub = str.slice(seg.start, subEnd);
        const sx = startX + (seg.start > 0 ? ctx.measureText(str.slice(0, seg.start)).width : 0);
        ctx.globalAlpha = alpha;
        ctx.fillStyle = seg.color;
        if (halo) {
          ctx.strokeStyle = halo;
          ctx.lineWidth = haloWidth;
          ctx.lineJoin = "round";
          ctx.strokeText(sub, sx, y);
        }
        ctx.fillText(sub, sx, y);
      }
      if (!isDone && wholeCount >= seg.start && wholeCount < seg.end && frac > 0.02) {
        const nextChar = str[wholeCount];
        const cx = startX + (wholeCount > 0 ? ctx.measureText(str.slice(0, wholeCount)).width : 0);
        ctx.globalAlpha = alpha * smooth(0, 1, frac);
        ctx.fillStyle = seg.color;
        if (halo) {
          ctx.strokeStyle = halo;
          ctx.lineWidth = haloWidth;
          ctx.lineJoin = "round";
          ctx.strokeText(nextChar, cx, y);
        }
        ctx.fillText(nextChar, cx, y);
      }
    }

    if (caret) {
      const shownCount = isDone ? str.length : wholeCount + (frac > 0.02 ? 1 : 0);
      const caretOffsetX = shownCount >= str.length
        ? fullWidth
        : shownCount > 0
          ? ctx.measureText(str.slice(0, shownCount)).width
          : 0;
      const cw = Math.max(2.2, finalSize * 0.085);
      const ch = finalSize * 0.78;
      const cx = startX + caretOffsetX + Math.max(3.5, finalSize * 0.12);
      const cy = y - finalSize * 0.72;
      roundRect(cx, cy, cw, ch, cw * 0.45, {
        fill: caretColor,
        alpha: alpha * caretAlpha,
      });
    }
    ctx.restore();
  }


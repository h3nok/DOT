  function getMembranePoints(cx, cy, radius, { amplitude, lobes, phase = 0 }) {
    const steps = 96;
    const pts = [];
    for (let step = 0; step <= steps; step++) {
      const u = (step / steps) * TAU;
      const r =
        radius +
        amplitude *
          (0.7 * Math.sin(lobes * u + phase) + 0.3 * Math.sin((lobes + 3) * u + phase * 1.7));
      pts.push([cx + Math.cos(u) * r, cy + Math.sin(u) * r]);
    }
    return pts;
  }


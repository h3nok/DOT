  function wrapFilmCopy(text, width, size, weight = 500, family = "Inter") {
    ctx.save();
    ctx.font = `${weight} ${size}px "${family}"`;
    if ("letterSpacing" in ctx) ctx.letterSpacing = "0px";
    const lines = [];
    let current = "";
    const words = text.replace(/\bBig C\b/g, "Big\u00a0C").replace(/\bLittle c\b/g, "Little\u00a0c").split(/[ \t\n]+/);
    for (const word of words) {
      const candidate = current ? `${current} ${word}` : word;
      if (current && ctx.measureText(candidate).width > width) {
        lines.push(current);
        current = word;
      } else current = candidate;
    }
    if (current) lines.push(current);
    ctx.restore();
    return lines;
  }

